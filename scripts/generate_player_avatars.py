"""Generate matching offline web and Compose vector portraits from shared SVG sources."""
from pathlib import Path
import json
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
svg_by_name = {}
for name in ('neutral', 'male', 'female', 'robot'):
    svg = (ROOT / f'design-system/avatars/{name}.svg').read_text().strip()
    svg_by_name[name] = svg
    paths = []
    for node in ET.fromstring(svg):
        tag = node.tag.split('}')[-1]
        a = node.attrib
        if tag == 'path':
            data = a['d']
        elif tag in ('ellipse', 'circle'):
            x, y = (float(a[k]) for k in ('cx', 'cy'))
            rx = float(a['r'] if tag == 'circle' else a['rx'])
            ry = float(a['r'] if tag == 'circle' else a['ry'])
            data = f'M{x-rx},{y}a{rx},{ry} 0 1,0 {2*rx},0a{rx},{ry} 0 1,0 {-2*rx},0'
        elif tag == 'rect':
            x, y, w, h = (float(a[k]) for k in ('x', 'y', 'width', 'height'))
            rx = min(float(a.get('rx', 0)), w / 2)
            ry = min(float(a.get('ry', a.get('rx', 0))), h / 2)
            data = (f'M{x+rx},{y}H{x+w-rx}a{rx},{ry} 0 0,1 {rx},{ry}'
                    f'V{y+h-ry}a{rx},{ry} 0 0,1 {-rx},{ry}'
                    f'H{x+rx}a{rx},{ry} 0 0,1 {-rx},{-ry}'
                    f'V{y+ry}a{rx},{ry} 0 0,1 {rx},{-ry}z')
        else:
            raise ValueError(tag)
        attrs = {'android:pathData': data, 'android:fillColor': a.get('fill', '#000000').replace('none', '#00000000').replace('white', '#FFFFFF')}
        for source, target in [('stroke', 'strokeColor'), ('stroke-width', 'strokeWidth'), ('stroke-linecap', 'strokeLineCap')]:
            if source in a:
                attrs['android:' + target] = a[source]
        paths.append('    <path ' + ' '.join(f'{k}="{v}"' for k, v in attrs.items()) + '/>')
    xml = '<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="64dp" android:height="64dp" android:viewportWidth="64" android:viewportHeight="64">\n' + '\n'.join(paths) + '\n</vector>\n'
    (ROOT / f'composeApp/src/commonMain/composeResources/drawable/avatar_{name}.xml').write_text(xml)
(ROOT / 'web/dice-scene/src/player-avatars.ts').write_text('// Generated by scripts/generate_player_avatars.py.\nexport const playerAvatars = ' + json.dumps(svg_by_name, ensure_ascii=False, indent=2) + ' as const;\n')
