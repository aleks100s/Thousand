#!/usr/bin/env python3
"""Generate committed Compose and web tokens; --check verifies they are current."""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

def generate():
    data = json.loads((ROOT / "design-system/tokens.json").read_text())
    def kotlin_color(value):
        raw = value.removeprefix("#")
        assert len(raw) in (6, 8)
        return "FF" + raw if len(raw) == 6 else raw[-2:] + raw[:6]
    def kebab(value):
        return re.sub(r"(?<!^)(?=[A-Z])", "-", value).lower()
    kotlin = "// Generated by scripts/generate_design_tokens.py. Edit design-system/tokens.json.\n"
    kotlin += "package com.alextos.thousand.application.theme\n\nimport androidx.compose.ui.graphics.Color\nimport androidx.compose.ui.unit.dp\n\nobject AppColors {\n"
    kotlin += "".join(f"    val {key} = Color(0x{kotlin_color(value)})\n" for key, value in data["colors"].items())
    kotlin += "}\n\nobject AppDimens {\n"
    kotlin += "".join(f"    val {key} = {value}.dp\n" for key, value in data["dimensions"].items()) + "}\n"
    css = "/* Generated by scripts/generate_design_tokens.py. */\n:root {\n"
    css += "".join(f"  --app-{kebab(key)}: {value};\n" for key, value in data["colors"].items())
    for key, value in data["colors"].items():
        rgb = ", ".join(str(int(value[index:index + 2], 16)) for index in (1, 3, 5))
        css += f"  --app-{kebab(key)}-rgb: {rgb};\n"
    css += "".join(f"  --app-{kebab(key)}: {value}px;\n" for key, value in data["dimensions"].items()) + "}\n"
    ts = "// Generated by scripts/generate_design_tokens.py.\nexport const designColors = " + json.dumps(data["colors"], indent=2) + " as const;\n"
    return {
        ROOT / "composeApp/src/commonMain/kotlin/com/alextos/thousand/application/theme/AppTokens.kt": kotlin,
        ROOT / "web/dice-scene/src/design-tokens.css": css,
        ROOT / "web/dice-scene/src/design-tokens.ts": ts,
    }

if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale = []
    for path, content in generate().items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.write_text(content)
    if stale:
        raise SystemExit("Stale design tokens: " + ", ".join(stale))
    print("Design tokens verified" if args.check else "Design tokens generated")
